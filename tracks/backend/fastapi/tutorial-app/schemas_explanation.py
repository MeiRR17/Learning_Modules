"""
הסבר Schemas - מה זה ולמה זה חשוב
"""

# ======== מה שיש לנו במסד נתונים (Database Model) ========
# זה מה שמאוחסן בפועל במסד הנתונים
class ItemInDatabase:
    id = 1                    # מזהה ייחודי (נוצר אוטומטית)
    name = "iPhone 15"        # שם המוצר
    description = "סמארטפון חדש"  # תיאור
    price = 3999.0           # מחיר
    in_stock = True          # האם זמין במלאי
    created_at = "2024-01-15 10:30:00"  # מתי נוצר

# ======== מה שהמשתמש שולח ל-API (Request Schema) ========
# כשמשתמש יוצר פריט חדש, הוא שולח רק את השדות האלה
class ItemCreateRequest:
    name = "iPhone 15"        # המשתמש מכניס שם
    description = "סמארטפון חדש"  # המשתמש מכניס תיאור (אופציונלי)
    price = 3999.0           # המשתמש מכניס מחיר
    # לא שולחים: id, in_stock, created_at - אלה נוצרים אוטומטית

# ======== מה שה-API מחזיר למשתמש (Response Schema) ========
# כשהמשתמש מבקש פריט, ה-API מחזיר את זה
class ItemResponse:
    id = 1                    # כן - צריך להראות את המזהה
    name = "iPhone 15"        # כן - שם המוצר
    description = "סמארטפון חדש"  # כן - תיאור
    price = 3999.0           # כן - מחיר
    in_stock = True          # כן - סטטוס מלאי
    created_at = "2024-01-15 10:30:00"  # כן - תאריך יצירה

# ======== מה שהמשתמש שולח לעדכון (Update Schema) ========
# כשמשתמש מעדכן פריט, הוא יכול לשנות רק חלק מהשדות
class ItemUpdateRequest:
    name = None               # אופציונלי - אם לא שולחים, לא משנים
    description = "סמארטפון חדש עם מצלמה משופרת"  # אופציונלי
    price = 3799.0           # אופציונלי - הורדנו מחיר
    in_stock = False         # אופציונלי - אולי נגמר המלאי
    # לא שולחים: id, created_at - אלה לא משתנים

"""
למה זה חשוב?
1. בטיחות: המשתמש לא יכול לשנות שדות שהוא לא אמור לשנות (כמו id או created_at)
2. גמישות: לפעמים רוצים להראות פחות מידע (למשל ברשימה לא מראים את כל הפרטים)
3. ולידציה: בודקים שהמידע שהמשתמש שולח תקין (למשל שהמחיר הוא מספר)
4. תיעוד: המשתמש יודע בדיוק מה לשלוח ומה לצפות לקבל
"""

