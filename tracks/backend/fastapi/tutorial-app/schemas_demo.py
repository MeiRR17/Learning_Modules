# זה מה שקורה בפועל כשמשתמש יוצר פריט חדש:

# 1. המשתמש שולח POST request ל-/items/ עם זה:
user_request = {
    "name": "לפטופ חדש",
    "description": "לפטופ עם מסך 15 אינץ'",
    "price": 3500.0
}

# 2. FastAPI מקבל את זה דרך ItemCreate schema:
# ItemCreate בודק שהמידע תקין:
# ✓ name הוא string וחובה
# ✓ description הוא string ואופציונלי
# ✓ price הוא float וחובה
# ✗ אם המשתמש היה שולח "id": 123, היה מתעלם מזה

# 3. הקוד יוצר אובייקט מהמסד נתונים:
database_item = {
    "id": None,              # יווצר אוטומטית
    "name": "לפטופ חדש",    # מהבקשה
    "description": "לפטופ עם מסך 15 אינץ'",  # מהבקשה
    "price": 3500.0,         # מהבקשה
    "in_stock": True,        # ברירת מחדל
    "created_at": "2024-01-15 10:30:00"  # אוטומטי
}

# 4. אחרי שמירה במסד הנתונים, ה-API מחזיר דרך ItemResponse:
api_response = {
    "id": 1,                              # כן - נוצר במסד הנתונים
    "name": "לפטופ חדש",                # כן - מהבקשה
    "description": "לפטופ עם מסך 15 אינץ'",  # כן - מהבקשה
    "price": 3500.0,                      # כן - מהבקשה
    "in_stock": True,                     # כן - ברירת מחדל
    "created_at": "2024-01-15T10:30:00"   # כן - נוצר אוטומטית
}

# ======== דוגמה לעדכון ========
# משתמש רוצה לעדכון רק מחיר:
update_request = {
    "price": 3200.0
}

# ItemUpdate schema מאפשר שדות אופציונליים:
# ✓ name אופציונלי - לא שולחים, לא משנים
# ✓ description אופציונלי - לא שולחים, לא משנים  
# ✓ price אופציונלי - שולחים 3200.0, מעדכנים
# ✓ in_stock אופציונלי - לא שולחים, לא משנים

# ======== למה זה טוב? ========
"""
1. שמירה על עקרונות:
   - מה שנכנס != מה שיוצא
   - המשתמש שולח רק מה שצריך
   - ה-API מחזיר רק מה שמורשה

2. בטיחות:
   - מניעת הזרקת נתונים (SQL Injection)
   - בדיקת סוגי נתונים
   - שדות חובה vs אופציונליים

3. גמישות:
   - אפשר ליצור schemas שונים למצבים שונים
   - אפשר להסתיר שדות רגישים
   - אפשר להוסיף ולידציה מתקדמת

4. תיעוד אוטומטי:
   - Swagger יודע להציג בדיוק מה לשלוח
   - דוגמאות אוטומטיות
   - טיפוסים ברורים
"""

